# Python Foundations
# 02 - Data Types

name = "Bilal"       # String
age = 20             # Integer
height = 5.9         # Float
is_student = True    # Boolean

print("Name:", name)
print("Type:", type(name))

print("Age:", age)
print("Type:", type(age))

print("Height:", height)
print("Type:", type(height))

print("Student:", is_student)
print("Type:", type(is_student))
